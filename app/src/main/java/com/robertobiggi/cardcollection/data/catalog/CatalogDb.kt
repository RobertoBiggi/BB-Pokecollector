package com.robertobiggi.cardcollection.data.catalog

import android.database.Cursor
import android.database.sqlite.SQLiteDatabase
import com.robertobiggi.cardcollection.core.image.CatalogImageSource
import com.robertobiggi.cardcollection.core.model.CatalogCard
import com.robertobiggi.cardcollection.core.model.CatalogVariant
import com.robertobiggi.cardcollection.core.model.Language
import com.robertobiggi.cardcollection.core.model.PokemonNames
import com.robertobiggi.cardcollection.core.model.VariantType
import java.io.Closeable
import java.io.File

/** The catalog file is not a valid card database (different format or version, damaged file). */
class InvalidCatalogException(message: String, cause: Throwable? = null) : Exception(message, cause)

/**
 * Set of the catalog, for the list from which to create a set collection.
 * @property id id of the set (e.g. "base1", "SM10a").
 * @property name name of the set.
 * @property cards cards of the set in the catalog.
 * @property declared cards declared by the set (official or total number), if known.
 * @property nameEn English name of a Japanese set, null if the set has none or it equals [name].
 */
data class CatalogSet(val id: String, val name: String, val cards: Int, val declared: Int?, val releaseDate: String?, val code: String? = null, val nameEn: String? = null)

/** Card found by a search, with what is needed to show it in the list. */
data class CardBrief(val id: String, val localId: String, val name: String, val setName: String, val imageUrl: String?)

/**
 * Reading of the card database (`cards.sqlite`, generated by the Card-collector-db-gen repository), read-only.
 * The file contains the cards of all Pokémon, already matched to Cardmarket and CardTrader: the app no longer queries any remote catalog.
 * An instance must be closed with [close]; queries are synchronous, so they must be called off the UI thread.
 */
class CatalogDb private constructor(private val db: SQLiteDatabase, val generatedAt: String, val languages: Set<String>) : Closeable {

    private val variantTypes: Map<Int, VariantType> = readEnum("variantType").mapNotNull { (code, name) -> VariantType.fromName(name)?.let { code to it } }.toMap()

    /** Columns of the `card` table: those added after the first version (nameEn, image paths) may be missing from files generated earlier, which stay valid. */
    private val cardColumns: Set<String> = db.rawQuery("PRAGMA table_info(card)", null).use { c ->
        buildSet { while (c.moveToNext()) add(c.getString(1)) }
    }

    /** True if `card_set` has the English name of the sets (added after the first version, may be missing from older files). */
    private val hasSetNameEn: Boolean = db.rawQuery("PRAGMA table_info(card_set)", null).use { c ->
        var found = false
        while (c.moveToNext()) if (c.getString(1) == "nameEn") found = true
        found
    }

    /** True if the file has `card_promo`, the date and event of the Japanese promos without a number (added after the first version). */
    private val hasCardPromo: Boolean = db.rawQuery("SELECT 1 FROM sqlite_master WHERE type = 'table' AND name = 'card_promo'", null).use { it.moveToFirst() }

    /** Columns of the `card_variant` table (the image paths of the variants were added after the first version). */
    private val variantColumns: Set<String> = db.rawQuery("PRAGMA table_info(card_variant)", null).use { c ->
        buildSet { while (c.moveToNext()) add(c.getString(1)) }
    }

    /**
     * Images that the database has for some variants of a card (prints with a stamp, from pokumon.com), apart from the card's own image.
     * @param cardId String - local id of the card.
     * @return List<CatalogVariantImage> - one per variant with an image; empty if there are none or this file has no such column.
     */
    fun variantImages(cardId: String): List<CatalogVariantImage> {
        if ("pokumon" !in variantColumns) return emptyList()
        db.rawQuery(
            "SELECT v.type, v.print, v.pokumon FROM card_variant v JOIN card c ON c.n = v.n WHERE c.id = ? AND v.pokumon IS NOT NULL ORDER BY v.type, v.print",
            arrayOf(cardId),
        ).use { c ->
            val found = ArrayList<CatalogVariantImage>()
            while (c.moveToNext()) {
                val type = variantTypes[c.getInt(0)] ?: continue
                found += CatalogVariantImage(type, c.getString(1), c.getString(2))
            }
            return found
        }
    }

    /** True if the database has the `card.nameEn` column (it shows the original names otherwise). */
    private val hasNameEn: Boolean = "nameEn" in cardColumns

    /**
     * Paths of the images that an image source has for some cards, from the source's column of the database.
     * @param source CatalogImageSource - image source.
     * @param cardIds Collection<String> - local ids of the cards.
     * @return Map<String, String> - path by card id, only for the cards the source has; empty if this file has no column for the source.
     */
    fun imagePaths(source: CatalogImageSource, cardIds: Collection<String>): Map<String, String> {
        if (source.column !in cardColumns) return emptyMap()
        val found = HashMap<String, String>()
        for (chunk in cardIds.chunked(SQL_CHUNK)) {
            db.rawQuery(
                "SELECT id, ${source.column} FROM card WHERE ${source.column} IS NOT NULL AND id IN (${chunk.joinToString(",") { "?" }})",
                chunk.toTypedArray(),
            ).use { c -> while (c.moveToNext()) found[c.getString(0)] = c.getString(1) }
        }
        return found
    }

    private fun readEnum(kind: String): Map<Int, String> =
        db.rawQuery("SELECT code, name FROM enum_code WHERE kind = ?", arrayOf(kind)).use { c ->
            buildMap { while (c.moveToNext()) put(c.getInt(0), c.getString(1)) }
        }

    /**
     * Sets of a language that have at least one card, in release order (most recent first).
     * @param language Language - catalog language.
     * @return List<CatalogSet> - available sets.
     */
    fun sets(language: Language): List<CatalogSet> {
        val nameEn = if (hasSetNameEn) "s.nameEn" else "NULL"
        val date = if (hasCardPromo) "COALESCE(s.releaseDate, MIN(p.releaseDate))" else "s.releaseDate"
        return db.rawQuery(
            """SELECT s.setId, s.name, COUNT(c.n), COALESCE(s.cardCountTotal, s.cardCountOfficial), $date, s.setCode, $nameEn
               FROM card_set s JOIN card c ON c.s = s.s ${if (hasCardPromo) "LEFT JOIN card_promo p ON p.n = c.n" else ""} WHERE s.language = ?
               GROUP BY s.s ORDER BY $date IS NULL, $date DESC, s.name""",
            arrayOf(language.code),
        ).use { c -> buildList { while (c.moveToNext()) add(CatalogSet(c.getString(0), c.getString(1), c.getInt(2), if (c.isNull(3)) null else c.getInt(3), c.getString(4), c.getString(5)?.takeIf { it.isNotBlank() }, c.getString(6)?.takeIf { it.isNotBlank() })) } }
    }

    /**
     * Occasion on which a promo without a number was given out (e.g. "Communication Evolution Campaign").
     * @param cardId String - local id of the card.
     * @return String? - the event, or null if the database does not know it or has no such table.
     */
    fun promoEvent(cardId: String): String? {
        if (!hasCardPromo) return null
        return db.rawQuery("SELECT p.event FROM card_promo p JOIN card c ON c.n = p.n WHERE c.id = ?", arrayOf(cardId)).use { c ->
            if (c.moveToFirst()) c.getString(0)?.takeIf { it.isNotBlank() } else null
        }
    }

    /**
     * English name of a set, shown next to the original one of Japanese sets.
     * @param language Language - catalog language.
     * @param setId String - id of the set.
     * @return String? - the name, or null if the set has none or this file has no such column.
     */
    fun setNameEn(language: Language, setId: String): String? {
        if (!hasSetNameEn) return null
        return db.rawQuery("SELECT nameEn FROM card_set WHERE language = ? AND setId = ?", arrayOf(language.code, setId)).use { c ->
            if (c.moveToFirst()) c.getString(0)?.takeIf { it.isNotBlank() } else null
        }
    }

    /**
     * All the cards of a set.
     * @param language Language - catalog language.
     * @param setId String - id of the set.
     * @return List<CatalogCard> - cards of the set, in number order.
     */
    fun cardsOfSet(language: Language, setId: String): List<CatalogCard> =
        query("WHERE s.language = ? AND s.setId = ?", arrayOf(language.code, setId))

    /**
     * The cards of one or more Pokémon.
     * @param language Language - catalog language.
     * @param dexIds Collection<Int> - national Pokédex numbers.
     * @return List<CatalogCard> - cards that contain them (also "Pikachu & Zekrom GX").
     */
    fun cardsOfPokemon(language: Language, dexIds: Collection<Int>): List<CatalogCard> {
        if (dexIds.isEmpty()) return emptyList()
        val marks = dexIds.joinToString(",") { "?" }
        return query(
            "WHERE s.language = ? AND c.n IN (SELECT n FROM card_pokemon WHERE dexId IN ($marks))",
            arrayOf(language.code) + dexIds.map { it.toString() },
        )
    }

    /**
     * The cards matching a name: if the text is the name of one or more Pokémon (in any language)
     * the cards of those Pokémon, otherwise the cards whose name (or English name) contains the text.
     * @param language Language - catalog language.
     * @param text String - searched text.
     * @return List<CatalogCard> - cards found.
     */
    fun cardsByName(language: Language, text: String): List<CatalogCard> {
        val dex = PokemonNames.dexIdsMatching(text)
        if (dex.isNotEmpty()) return cardsOfPokemon(language, dex)
        val pattern = "%" + like(text) + "%"
        // Also the English name, so "Unidentified Fossil" finds the Japanese or German cards (なぞの化石, Unbekanntes Fossil).
        if (hasNameEn) {
            return query("WHERE s.language = ? AND (c.name LIKE ? ESCAPE '\\' OR c.nameEn LIKE ? ESCAPE '\\')", arrayOf(language.code, pattern, pattern))
        }
        return query("WHERE s.language = ? AND c.name LIKE ? ESCAPE '\\'", arrayOf(language.code, pattern))
    }

    /**
     * The cards with a printed number (e.g. "117/080", "SM190", "TG05"), possibly narrowed by code or words.
     * @param language Language - catalog language.
     * @param number Int - number searched (without leading zeros).
     * @param total Int? - printed total of the set, if given.
     * @param tokens List<String> - set code or id and parts of the name.
     * @return List<CatalogCard> - cards found, narrowing with total and words only as long as something remains.
     */
    fun cardsByCode(language: Language, number: Int, total: Int?, tokens: List<String>): List<CatalogCard> {
        var hits = query(
            "WHERE s.language = ? AND c.localId NOT GLOB '*[^0-9]*' AND LENGTH(c.localId) <= 6 AND CAST(c.localId AS INTEGER) = ?",
            arrayOf(language.code, number.toString()),
        )
        if (total != null) hits = hits.narrow { (it.printedNumber.substringAfter('/', "").toIntOrNull() ?: total) == total }
        for (token in tokens) {
            val inSet = hits.filter { it.setId.equals(token, true) || it.setCode.equals(token, true) }
            hits = if (inSet.isNotEmpty()) inSet else hits.narrow { it.name.contains(token, ignoreCase = true) }
        }
        return hits
    }

    /**
     * A card with its variants.
     * @param cardId String - local id ("language:tcgdexId").
     * @return CatalogCard? - the card, or null if the catalog does not contain it.
     */
    fun card(cardId: String): CatalogCard? = query("WHERE c.id = ?", arrayOf(cardId)).firstOrNull()

    private fun query(where: String, args: Array<String>): List<CatalogCard> {
        val rows = db.rawQuery(
            """SELECT c.n, c.id, s.language, c.name, s.setId, s.name, s.setCode, s.serieId, s.serieName, c.localId, c.printedNumber, c.rarity,
                      ${if (hasCardPromo) "COALESCE(p.releaseDate, s.releaseDate)" else "s.releaseDate"}, c.illustrator, c.dexId, c.cardmarketId, c.cardmarketExpansionId, c.cardmarketName, c.cardmarketProductHint,
                      c.cmProduct, c.cardTraderBlueprintId, s.cardTraderExpansionId, c.origin, ${if (hasNameEn) "c.nameEn" else "NULL"}
               FROM card c JOIN card_set s ON s.s = c.s ${if (hasCardPromo) "LEFT JOIN card_promo p ON p.n = c.n" else ""} $where ORDER BY s.setId, c.localId""",
            args,
        ).use { c -> buildList { while (c.moveToNext()) add(Row(c)) } }
        val variants = HashMap<Long, MutableList<CatalogVariant>>()
        for (chunk in rows.map { it.n }.chunked(SQL_CHUNK)) {
            db.rawQuery(
                "SELECT n, type, print, cardmarketId, cardTraderBlueprintId FROM card_variant WHERE n IN (${chunk.joinToString(",")}) ORDER BY n, type, print",
                null,
            ).use { c ->
                while (c.moveToNext()) {
                    val type = variantTypes[c.getInt(1)] ?: continue
                    variants.getOrPut(c.getLong(0)) { ArrayList() } += CatalogVariant(type, if (c.isNull(3)) null else c.getInt(3), c.getString(2), if (c.isNull(4)) null else c.getInt(4))
                }
            }
        }
        return rows.mapNotNull { r -> r.toCard(variants[r.n].orEmpty()) }
    }

    private inner class Row(c: Cursor) {
        val n = c.getLong(0)
        val id = c.getString(1)
        val language = c.getString(2)
        /** English name if the database knows it, otherwise that of the card's language. */
        val name: String = c.getString(23) ?: c.getString(3)
        val setId = c.getString(4)
        val setName = c.getString(5)
        val setCode: String? = c.getString(6)
        val serieId: String? = c.getString(7)
        val serieName: String? = c.getString(8)
        val localId = c.getString(9)
        val printedNumber = c.getString(10)
        val rarity: String? = c.getString(11)
        val releaseDate: String? = c.getString(12)
        val illustrator: String? = c.getString(13)
        val dexId = if (c.isNull(14)) null else c.getInt(14)
        val cardmarketId = if (c.isNull(15)) null else c.getInt(15)
        val cardmarketExpansionId = if (c.isNull(16)) null else c.getInt(16)
        val cardmarketName: String? = c.getString(17)
        val productHint = if (c.isNull(18)) null else c.getInt(18)
        val product = if (c.isNull(19)) null else c.getInt(19)
        val blueprint = if (c.isNull(20)) null else c.getInt(20)
        val ctExpansion = if (c.isNull(21)) null else c.getInt(21)
        val fromTcgdex = c.getInt(22) == ORIGIN_TCGDEX

        fun toCard(variants: List<CatalogVariant>): CatalogCard? {
            val lang = Language.fromCode(language) ?: return null
            return CatalogCard(
                id = id, language = lang, tcgdexId = id.substringAfter(':'), name = name, setId = setId, setName = setName, setCode = setCode,
                serieId = serieId, serieName = serieName, localId = localId, printedNumber = printedNumber, rarity = rarity, releaseDate = releaseDate,
                illustrator = illustrator,
                // Images are on TCGdex, with an address derived from the id; cards from other sources do not have one.
                imageBaseUrl = if (fromTcgdex && serieId != null) "$IMAGE_HOST/$language/$serieId/$setId/$localId" else null,
                variants = variants.ifEmpty { listOf(CatalogVariant(VariantType.NORMAL)) }, dexId = dexId, cardmarketId = cardmarketId,
                cardmarketExpansionId = cardmarketExpansionId, cardmarketName = cardmarketName, cardmarketProductHint = productHint,
                cardmarketProduct = product, cardTraderBlueprintId = blueprint, cardTraderExpansionId = ctExpansion,
            )
        }
    }

    override fun close() = db.close()

    companion object {
        /** Version of the format the app can read (`meta.schemaVersion`, see `SCHEMA_VERSION` in `gen_card_db.py` of Card-collector-db-gen). */
        const val SCHEMA_VERSION = 2
        private const val ORIGIN_TCGDEX = 0
        private const val SQL_CHUNK = 500
        private const val IMAGE_HOST = "https://assets.tcgdex.net"

        /**
         * Opens the file read-only and checks its format.
         * @param file File - card database.
         * @return CatalogDb - open database.
         * @throws InvalidCatalogException if the file is not a valid database or has a different version.
         */
        fun open(file: File): CatalogDb {
            val db = try {
                SQLiteDatabase.openDatabase(file.path, null, SQLiteDatabase.OPEN_READONLY)
            } catch (e: Exception) {
                throw InvalidCatalogException("File non apribile", e)
            }
            try {
                val meta = db.rawQuery("SELECT key, value FROM meta", null).use { c -> buildMap { while (c.moveToNext()) put(c.getString(0), c.getString(1)) } }
                if (meta["schemaVersion"]?.toIntOrNull() != SCHEMA_VERSION) throw InvalidCatalogException("Versione del database non supportata: ${meta["schemaVersion"]}")
                return CatalogDb(db, meta["generatedAt"].orEmpty(), meta["languages"].orEmpty().split(',').filter { it.isNotEmpty() }.toSet())
            } catch (e: InvalidCatalogException) {
                db.close()
                throw e
            } catch (e: Exception) {
                db.close()
                throw InvalidCatalogException("Database non valido", e)
            }
        }

        private fun like(text: String) = text.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")

        private fun <T> List<T>.narrow(predicate: (T) -> Boolean): List<T> = filter(predicate).ifEmpty { this }
    }
}

/**
 * Image of a variant in the card database.
 * @property type VariantType - type of the variant.
 * @property print String - stamp that tells it apart from the others of the same type.
 * @property path String - path of the image on the site of its source (rebuilt into an address by the source's [com.robertobiggi.cardcollection.core.image.CatalogImageSource]).
 */
data class CatalogVariantImage(val type: VariantType, val print: String, val path: String)
