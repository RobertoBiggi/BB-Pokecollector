package com.robertobiggi.cardcollection.data.local

import android.content.Context
import androidx.room.Database
import androidx.room.Room
import androidx.room.RoomDatabase

/** Local database: it is the only data source of the UI, so the app works offline. */
@Database(
    entities = [
        CollectionEntity::class,
        TrackedQueryEntity::class,
        CardEntity::class,
        CardVariantEntity::class,
        CollectionCardEntity::class,
        CollectionEntryEntity::class,
        PriceSnapshotEntity::class,
        PriceRunEntity::class,
        PriceAlertEntity::class,
    ],
    version = 19,
    exportSchema = true,
)
abstract class AppDatabase : RoomDatabase() {
    /**
     * Access to collections, searches, cards and variants.
     * @return CatalogDao - DAO generated by Room.
     */
    abstract fun catalogDao(): CatalogDao

    /**
     * Access to the user data of each collection.
     * @return CollectionDao - DAO generated by Room.
     */
    abstract fun collectionDao(): CollectionDao

    /**
     * Access to prices and the update log.
     * @return PriceDao - DAO generated by Room.
     */
    abstract fun priceDao(): PriceDao

    companion object {
        private const val NAME = "card-collection.db"

        /**
         * Creates the database. On first install it is empty, with no collections or searches.
         * @param context Context - application context.
         * @return AppDatabase - database instance.
         */
        fun create(context: Context): AppDatabase =
            Room.databaseBuilder(context.applicationContext, AppDatabase::class.java, NAME)
                .addMigrations(*Migrations.ALL)
                .build()
    }
}
